import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import nunjucks from "nunjucks";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = path.join(projectRoot, "src");

const pages = [
  { template: "pages/index.njk", output: "index.html", language: "fr" },
  { template: "pages/uk-version.njk", output: "uk-version.html", language: "en" }
];

const templates = new nunjucks.Environment(
  new nunjucks.FileSystemLoader(sourceRoot, { noCache: true }),
  {
    autoescape: true,
    throwOnUndefined: true,
    trimBlocks: true,
    lstripBlocks: true
  }
);

const renderedPages = pages.map(({ template, output, language }) => {
  const html = templates.render(template, { language }).trim();

  if (!html.startsWith("<!DOCTYPE html>")) {
    throw new Error(`${template} must render a complete HTML document.`);
  }

  if (!html.includes(`<html lang="${language}">`)) {
    throw new Error(`${template} must declare lang="${language}".`);
  }

  return {
    output,
    html: `${html.replace(
      "<!DOCTYPE html>",
      "<!DOCTYPE html>\n<!-- Generated by yarn build. Edit files in src/ instead. -->"
    )}\n`
  };
});

await Promise.all(
  renderedPages.map(({ output, html }) =>
    writeFile(path.join(projectRoot, output), html, "utf8")
  )
);

console.log(`Generated ${renderedPages.length} localized pages.`);
