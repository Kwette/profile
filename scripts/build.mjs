import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import nunjucks from "nunjucks";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = path.join(projectRoot, "src");
const outputRoot = path.join(projectRoot, "dist");

const pages = [
  { template: "pages/portfolio.njk", data: "data/fr.json", output: "index.html", language: "fr" },
  { template: "pages/portfolio.njk", data: "data/en.json", output: "uk-version.html", language: "en" }
];

const styleSources = [
  "styles/tokens.css",
  "styles/base.css",
  "styles/utilities.css",
  "styles/components/buttons.css",
  "styles/layout.css",
  "styles/components/cards.css",
  "styles/components/hero.css",
  "styles/components/selected-project.css",
  "styles/components/technical-focus.css",
  "styles/components/resume-document.css",
  "styles/components/content-disclosure.css",
  "styles/components/project-disclosure.css",
  "styles/components/archive-entry.css",
  "styles/components/archive-dialog.css",
  "styles/components/professional-experience.css",
  "styles/components/experience-dialog.css",
  "styles/components/interaction-effects.css",
  "styles/components/personal-project.css",
  "styles/components/project-archive.css",
  "styles/components/footer.css",
  "styles/components/resume-responsive.css",
  "styles/components/navigation.css",
  "styles/components/social-contact.css",
  "styles/components/project-card.css",
  "styles/components/experience-card.css",
  "styles/components/dialog.css",
  "styles/components/carousel.css",
  "styles/components/resume-controls.css",
  "styles/components/resume.css"
];

const templates = new nunjucks.Environment(
  new nunjucks.FileSystemLoader(sourceRoot, { noCache: true }),
  {
    autoescape: true,
    throwOnUndefined: true,
    trimBlocks: true,
    lstripBlocks: true
  }
);

templates.addFilter("json", value => JSON.stringify(value));

const renderedPages = await Promise.all(pages.map(async ({ template, data, output, language }) => {
  const pageData = JSON.parse(await readFile(path.join(sourceRoot, data), "utf8"));

  if (pageData.language !== language) {
    throw new Error(`${data} must declare language "${language}".`);
  }

  const html = templates.render(template, pageData).trim();

  if (!html.startsWith("<!DOCTYPE html>")) {
    throw new Error(`${template} must render a complete HTML document.`);
  }

  if (!html.includes(`<html lang="${language}">`)) {
    throw new Error(`${template} must declare lang="${language}".`);
  }

  return {
    output,
    html: `${html.replace(
      "<!DOCTYPE html>",
      "<!DOCTYPE html>\n<!-- Generated by yarn build. Edit files in src/ instead. -->"
    )}\n`
  };
}));

const stylesheet = (
  await Promise.all(
    styleSources.map(file => readFile(path.join(sourceRoot, file), "utf8"))
  )
).join("");

await rm(outputRoot, { recursive: true, force: true });
await mkdir(outputRoot, { recursive: true });

await Promise.all([
  ...renderedPages.map(({ output, html }) =>
    writeFile(path.join(outputRoot, output), html, "utf8")
  ),
  writeFile(path.join(outputRoot, "style.css"), stylesheet, "utf8"),
  cp(path.join(sourceRoot, "scripts"), path.join(outputRoot, "scripts"), {
    recursive: true
  })
]);

const staticEntries = ["images"];

await Promise.all(
  staticEntries.map(entry =>
    cp(path.join(projectRoot, entry), path.join(outputRoot, entry), {
      recursive: true,
      filter: source => path.basename(source) !== ".DS_Store"
    })
  )
);

console.log(`Generated ${renderedPages.length} localized pages in dist/.`);
